import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('artifacts', {recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text())});
// Exercise the real async-library race, rather than relying on a warm cache.
await page.route('**/vendor/three-r128.min.js',async route=>{await new Promise(r=>setTimeout(r,1200));await route.continue()});
await page.goto('http://127.0.0.1:3011',{waitUntil:'networkidle'});
await page.waitForTimeout(2500);
assert.equal(await page.locator('#bg').evaluate(c=>!c.hidden && c.width>0),true);
assert.equal(await page.evaluate(()=>!!window.THREE),true);
await page.screenshot({path:'artifacts/hero-3d-desktop.png'});
const first=await page.locator('#bg').screenshot();
await page.waitForTimeout(500);
const second=await page.locator('#bg').screenshot();
assert.equal(first.equals(second),false,'Sculpture animates at rest');
await page.locator('#build').evaluate(el=>scrollTo({top:el.offsetTop,behavior:'instant'}));
await page.waitForTimeout(1600);
await page.screenshot({path:'artifacts/hero-3d-scroll.png'});
await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(1200);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.screenshot({path:'artifacts/hero-3d-mobile.png'});
await page.emulateMedia({reducedMotion:'reduce'});
await page.waitForTimeout(400);
const reduced=await page.locator('#bg').screenshot();
await page.waitForTimeout(350);
assert.equal(reduced.equals(await page.locator('#bg').screenshot()),true,'Reduced motion is static');
await page.emulateMedia({reducedMotion:'no-preference'});
await page.waitForTimeout(350);
assert.equal(reduced.equals(await page.locator('#bg').screenshot()),false,'Animation resumes');
assert.deepEqual(errors,[]);
await writeFile('artifacts/hero-3d-check.json',JSON.stringify({passed:true,errors,checks:['Delayed Three.js initialization','WebGL rendering','Idle motion','Scroll transformation','Mobile overflow','Reduced motion','Live motion preference changes']},null,2));
console.log('PASS: 3D hero renders, animates, scrolls, fits mobile, and respects reduced motion; no browser errors.');
await browser.close();
